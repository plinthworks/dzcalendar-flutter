// Writes the zone data `dzcalendar_core` reads, from an IANA release.
//
//   dart run tool/encode_tzdata.dart <source dir> <zoneinfo dir> <out.dart> [<archive sums>]
//
// <source dir> holds the release's text files (africa, europe, backward…, and
// `version`); <zoneinfo dir> is what that release's own zic compiled from
// them. `tool/refresh_tzdata.sh` does the three steps. Only `dart:io`: the
// script runs before anything is resolved.
//
// Each zone becomes one string, read lazily by `lib/src/zone/zone_rules.dart`:
//
//   <initial offset>;<t>,<o>;<t>,<o>…|<rule from>|<POSIX footer>
//
// offsets in seconds east of UTC, times in seconds since the epoch, each time
// written as its difference from the one before, all in base 36. Only offset
// changes are kept (a change of name or of DST flag alone is not a
// transition for a calendar). The footer gives the rule after the file's last
// transition, so dates past 2037 keep their clock changes; that transition's
// time is kept as <rule from> (empty when the file has none) even when it
// changed no offset — Troll's 2005, Riga's 2001 — or the rule would reach
// back over years it never governed.

import 'dart:io';
import 'dart:typed_data';

const _sources = [
  'africa',
  'antarctica',
  'asia',
  'australasia',
  'europe',
  'northamerica',
  'southamerica',
  'etcetera',
  'backward',
];

void main(List<String> args) {
  if (args.length != 3 && args.length != 4) {
    stderr.writeln('usage: dart run tool/encode_tzdata.dart <source dir> <zoneinfo dir> <out.dart> [<archive sums>]');
    exit(64);
  }
  final [sourceDir, zoneinfoDir, outPath, ...rest] = args;
  final sums = rest.isEmpty ? <String>[] : rest.first.split(';');
  final version = File('$sourceDir/version').readAsStringSync().trim();

  final zones = <String>{};
  final links = <String, String>{};
  for (final name in _sources) {
    for (final raw in File('$sourceDir/$name').readAsLinesSync()) {
      final line = raw.split('#').first.trim();
      final words = line.split(RegExp(r'\s+'));
      if (words.length >= 2 && words[0] == 'Zone') zones.add(words[1]);
      if (words.length >= 3 && words[0] == 'Link') links[words[2]] = words[1];
    }
  }
  // A link names a zone; follow a chain if a release ever writes one.
  String target(String name) {
    var at = name;
    for (var hops = 0; links.containsKey(at); hops++) {
      if (hops > 8) throw StateError('link loop at $name');
      at = links[at]!;
    }
    return at;
  }

  final encoded = <String, String>{};
  for (final zone in zones.toList()..sort()) {
    encoded[zone] = _encode(_readTzif(File('$zoneinfoDir/$zone').readAsBytesSync(), zone));
  }
  final resolved = <String, String>{
    for (final link in links.keys.toList()..sort())
      if (!zones.contains(link)) link: target(link),
  };
  for (final MapEntry(:key, :value) in resolved.entries) {
    if (!encoded.containsKey(value)) throw StateError('$key links to $value, which is no zone');
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/encode_tzdata.dart from IANA tzdata $version. Do not edit;')
    ..writeln('// run tool/refresh_tzdata.sh. Format: tool/encode_tzdata.dart.');
  for (final sum in sums) {
    out.writeln('// $sum');
  }
  out
    ..writeln()
    ..writeln('/// The IANA release these rules come from.')
    ..writeln("const tzdataVersion = '$version';")
    ..writeln()
    ..writeln('const tzdataZones = <String, String>{');
  for (final MapEntry(:key, :value) in encoded.entries) {
    out.writeln("  '$key': '$value',");
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('const tzdataLinks = <String, String>{');
  for (final MapEntry(:key, :value) in resolved.entries) {
    out.writeln("  '$key': '$value',");
  }
  out.writeln('};');
  File(outPath).writeAsStringSync(out.toString());
  stdout.writeln('tzdata $version: ${encoded.length} zones, ${resolved.length} links → $outPath');
}

class _Tzif {
  _Tzif(this.initial, this.times, this.offsets, this.ruleFrom, this.footer);
  final int initial;
  final List<int> times;
  final List<int> offsets;
  final int? ruleFrom;
  final String footer;
}

/// RFC 8536: the version 2+ block (64-bit times) and its footer.
_Tzif _readTzif(Uint8List bytes, String zone) {
  final data = ByteData.sublistView(bytes);
  String magic(int at) => String.fromCharCodes(bytes.sublist(at, at + 4));
  if (magic(0) != 'TZif' || bytes[4] < 0x32) throw FormatException('$zone: not TZif v2+');

  int skipBlock(int at, int timeSize) {
    int count(int i) => data.getUint32(at + 20 + 4 * i);
    final [isut, isstd, leap, time, type, char] = [for (var i = 0; i < 6; i++) count(i)];
    return at + 44 + time * timeSize + time + type * 6 + char + leap * (timeSize + 4) + isstd + isut;
  }

  final v2 = skipBlock(0, 4);
  if (magic(v2) != 'TZif') throw FormatException('$zone: no second header');
  int count(int i) => data.getUint32(v2 + 20 + 4 * i);
  final timeCount = count(3);
  final typeCount = count(4);
  var at = v2 + 44;
  final times = [for (var i = 0; i < timeCount; i++) data.getInt64(at + 8 * i)];
  at += 8 * timeCount;
  final typeOf = [for (var i = 0; i < timeCount; i++) bytes[at + i]];
  at += timeCount;
  final utoff = [for (var i = 0; i < typeCount; i++) data.getInt32(at + 6 * i)];

  final end = skipBlock(v2, 8);
  final footerEnd = bytes.indexOf(0x0a, end + 1);
  final footer = String.fromCharCodes(bytes.sublist(end + 1, footerEnd));

  // Type 0 holds before the first transition (RFC 8536, 3.2).
  final initial = utoff[0];
  final outTimes = <int>[];
  final outOffsets = <int>[];
  var current = initial;
  for (var i = 0; i < timeCount; i++) {
    final offset = utoff[typeOf[i]];
    if (offset == current) continue;
    outTimes.add(times[i]);
    outOffsets.add(offset);
    current = offset;
  }
  if (footer.contains('|')) throw FormatException('$zone: footer holds the separator');
  return _Tzif(initial, outTimes, outOffsets, timeCount == 0 ? null : times.last, footer);
}

String _encode(_Tzif z) {
  final parts = [z.initial.toRadixString(36)];
  var previous = 0;
  for (var i = 0; i < z.times.length; i++) {
    parts.add('${(z.times[i] - previous).toRadixString(36)},${z.offsets[i].toRadixString(36)}');
    previous = z.times[i];
  }
  return '${parts.join(';')}|${z.ruleFrom?.toRadixString(36) ?? ''}|${z.footer}';
}
