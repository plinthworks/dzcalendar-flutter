// Writes packages/dzcalendar_core/lib/src/format/week_data.g.dart from the
// CLDR data of the Node.js running it (ICU's `Intl.Locale` week info and
// likely subtags): what the web reads from its engine, as a table, so the
// port gives the same first day of the week for a locale (19e-1 review).
//   node tool/week_data.mjs <languages…>   (the languages intl formats)
// Regions: every ISO 3166 alpha-2 code; only those whose week does not
// start on Monday are written. Likely regions: per language, and per
// language + script where the script moves the region (zh-Hant → TW).
import { writeFileSync } from 'node:fs';

const langs = process.argv.slice(2);
const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
const firstDay = {};
for (const a of letters) for (const b of letters) {
  const r = a + b;
  let info;
  try {
    const l = new Intl.Locale(`und-${r}`);
    info = typeof l.getWeekInfo === 'function' ? l.getWeekInfo() : l.weekInfo;
  } catch { continue; }
  const f = info?.firstDay;
  if (f && f !== 1) firstDay[r] = f;
}
const likely = {};
const scripts = ['Latn', 'Cyrl', 'Arab', 'Hans', 'Hant', 'Deva', 'Beng', 'Guru', 'Hebr'];
for (const lang of langs) {
  let base;
  try { base = new Intl.Locale(lang).maximize().region; } catch { continue; }
  if (base) likely[lang] = base;
  for (const s of scripts) {
    try {
      const r = new Intl.Locale(`${lang}-${s}`).maximize().region;
      if (r && r !== base) likely[`${lang}-${s}`] = r;
    } catch { /* not a tag */ }
  }
}
const entries = (o) => Object.keys(o).sort().map((k) => `  '${k}': ${typeof o[k] === 'number' ? o[k] : `'${o[k]}'`},`).join('\n');
writeFileSync(
  new URL('../packages/dzcalendar_core/lib/src/format/week_data.g.dart', import.meta.url),
  `// GENERATED by tool/week_data.mjs from the CLDR data of Node ${process.version}
// (ICU ${process.versions.icu}, CLDR ${process.versions.cldr ?? '?'}). Do not edit.

/// Regions whose week does not start on Monday: their first day (ISO 1–7).
const weekFirstDay = <String, int>{
${entries(firstDay)}
};

/// The likely region of a language (or language-Script) written without one.
const likelyRegion = <String, String>{
${entries(likely)}
};
`,
);
console.log(Object.keys(firstDay).length, 'regions,', Object.keys(likely).length, 'likely');
